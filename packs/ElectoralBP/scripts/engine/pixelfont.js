const ACCENTS = { À: "A", Á: "A", Â: "A", Ä: "A", Ã: "A", Å: "A", Ç: "C", È: "E", É: "E", Ê: "E", Ë: "E", Ì: "I", Í: "I", Î: "I", Ï: "I", Ñ: "N", Ò: "O", Ó: "O", Ô: "O", Ö: "O", Õ: "O", Ø: "O", Ù: "U", Ú: "U", Û: "U", Ü: "U", Ý: "Y", ß: "S" };

/** Text as the font can draw it: upper case, no colour codes, unknown letters as "?". */
export function fontText(text) {
  return String(text ?? "")
    .replace(/§./g, "")
    .toUpperCase()
    .split("")
    .map((c) => (G[c] ? c : ACCENTS[c] || "?"))
    .join("");
}

export const textWidth = (text) => {
  const t = fontText(text);
  return t.length ? t.length * 4 - 1 : 0;
};

/** Calls dot(x, y) for every lit pixel of the text, top-left at (x, y). */
export function eachTextPixel(text, x, y, dot) {
  const t = fontText(text);
  for (let k = 0; k < t.length; k++) {
    const g = G[t[k]];
    for (let row = 0; row < 5; row++) for (let col = 0; col < 3; col++) if (g[row][col] === "#") dot(x + k * 4 + col, y + row);
  }
}

/** Shortens text so it fits in `px` pixels. */
export function fitText(text, px) {
  let t = fontText(text);
  if (textWidth(t) <= px) return t;
  while (t.length > 1 && textWidth(`${t}.`) > px) t = t.slice(0, -1);
  return `${t}.`;
}
